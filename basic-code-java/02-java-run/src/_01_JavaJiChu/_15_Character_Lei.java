package _01_JavaJiChu;

public class _15_Character_Lei {
    /*
    Character 类用于对单个字符进行操作。
    Character 类在对象中包装一个基本类型 char 的值
    * */
    char ch = 'a';
    // Unicode 字符表示形式
    char uniChar = '\u039A';
    // 字符数组
    char[] charArray = {'a', 'b', 'c', 'd', 'e'};


    /*
    转义序列
    * */
/*
    \t	在文中该处插入一个tab键
    \b	在文中该处插入一个后退键
    \n	在文中该处换行
    \r	在文中该处插入回车
    \f	在文中该处插入换页符
    \'	在文中该处插入单引号
    \"	在文中该处插入双引号
    \\	在文中该处插入反斜杠
*/


    /*
    * 序号	方法与描述
      1	isLetter()
      是否是一个字母
      2	isDigit()
      是否是一个数字字符
      3	isWhitespace()
      是否是一个空白字符
      4	isUpperCase()
      是否是大写字母
      5	isLowerCase()
      是否是小写字母
      6	toUpperCase()
      指定字母的大写形式
      7	toLowerCase()
      指定字母的小写形式
      8	toString()
      返回字符的字符串形式，字符串的长度仅为1
      * */
}
