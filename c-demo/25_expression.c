
/*~~~~~~~~~~~~~~~~~~~~~~~~【强制类型转换  使用强制类型转换运算符把一个整数变量除以另一个整数变量，得到一个浮点数】~~~~~~~~~~~~~~~~~~~~~~~~~*/
#include <stdio.h>

int main()
{
   int sum = 17, count = 5;
   double mean;
 
   mean = (double) sum / count;
   printf("Value of mean : %f\n", mean );
 
}

